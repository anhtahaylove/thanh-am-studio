r"""Writes pyuni_tables.rs: the Unicode character classes of the Python that runs worker/main.py, so the Rust port of the
TTS text rules classifies every code point as Python 3.11 does (its Unicode 14 data, not Rust's newer tables).

Run with the private runtime from worker-rs/src/tts:  ..\..\..\runtime\python\python.exe -I gen_pyuni.py
"""
import re
import sys
import unicodedata

ALL = [chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out, start, prev = [], None, None
    for ch in ALL:
        c = ord(ch)
        if pred(ch):
            if start is None or c != prev + 1:
                if start is not None:
                    out.append((start, prev))
                start = c
            prev = c
    if start is not None:
        out.append((start, prev))
    return out


def decimal_runs():
    # (first, last, value of first): consecutive code points whose decimal values count up by one
    out = []
    for a, b in ranges(str.isdecimal):
        c = a
        while c <= b:
            v0, d = unicodedata.decimal(chr(c)), c
            while d + 1 <= b and unicodedata.decimal(chr(d + 1)) == unicodedata.decimal(chr(d)) + 1:
                d += 1
            out.append((c, d, v0))
            c = d + 1
    return out


def table(name, rows, doc):
    body = ''.join(f'    ({a:#x}, {b:#x}),\n' for a, b in rows)
    return f'/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{body}];\n'


# Letters of the case-insensitive pause-mark patterns (main.py PAUSE_MARK, PAUSE_VALUE): every code point `re` matches for each.
FOLD = sorted(set('nghỉpausemscoidây'))
fold_rows = []
for letter in FOLD:
    same = [ord(ch) for ch in ALL if re.fullmatch(re.escape(letter), ch, re.IGNORECASE)]
    fold_rows.append(f"    ('{letter}', &[{', '.join(f'{c:#x}' for c in same)}]),\n")

out = [
    f'// @generated by gen_pyuni.py with Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n',
    table('SPACE', ranges(str.isspace), '`str.isspace()`, which is also `re`\'s `\\s`.'),
    table('ALPHA', ranges(str.isalpha), '`str.isalpha()`.'),
    table('ALNUM', ranges(lambda ch: ch.isalnum() or ch == '_'), '`re`\'s `\\w`: `str.isalnum()` or `_`.'),
    table('DIGIT', ranges(str.isdigit), '`str.isdigit()`.'),
    '/// `str.isdecimal()` (`re`\'s `\\d`) as runs `(first, last, value of first)`; `float()` reads these digits.\n'
    'pub const DECIMAL: &[(u32, u32, u32)] = &[\n' + ''.join(f'    ({a:#x}, {b:#x}, {v}),\n' for a, b, v in decimal_runs()) + '];\n',
    '/// For each letter of the pause-mark patterns, the code points `re.IGNORECASE` matches it with.\n'
    'pub const FOLD: &[(char, &[u32])] = &[\n' + ''.join(fold_rows) + '];\n',
]
with open('pyuni_tables.rs', 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out))
